import json
from pathlib import Path

from esp_build.platformio import ENVIRONMENT_NAME, PLATFORM

OTA_APP_LIBRARY_DIR = Path(__file__).resolve().parents[2] / "device_lib" / "OtaApp"
DEVICE_CONFIG_RELATIVE_PATH = Path("src") / "device_config.cpp"

_PLATFORMIO_INI = """\
; Build with: tb esp-build build --dir .
; Add third-party libraries as extra indented lines under lib_deps (e.g. `adafruit/Adafruit BME280 Library`).
; The OtaApp line must stay: it is what keeps the device updatable over WiFi.
[env:{environment}]
platform = {platform}
board = {board}
framework = arduino
monitor_speed = 115200
lib_deps =
    symlink://{ota_app_library}
"""

_MAIN_CPP = """\
#include <Arduino.h>
#include <OtaApp.h>

// OtaApp defines setup() and loop() and keeps WiFi + OTA updates running in the background.
// Put application code in appSetup() and appLoop(). Do not define setup() or loop() here.
// WiFi is already connected when appSetup() runs (check WiFi.status() if it matters).
// Print with Log instead of Serial: `tb esp-logs --host <ip>` reads Log output over WiFi.

void appSetup() {
  Log.println("application started");
}

void appLoop() {
}
"""

_DEVICE_CONFIG_CPP = """\
// Generated by `tb esp-build init` from environment variables; rerun it to change these values.
// Contains secrets: do not commit.
#include <OtaApp.h>

const OtaAppConfig otaAppConfig = {{
  {wifi_ssid},
  {wifi_password},
  {hostname},
  {ota_password},
}};
"""

_GITIGNORE = f"""\
.pio/
{DEVICE_CONFIG_RELATIVE_PATH.as_posix()}
"""


def _c_string_literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def write_project(
    project_dir: Path, board: str, wifi_ssid: str, wifi_password: str, hostname: str, ota_password: str
) -> dict[str, list[str]]:
    """Creates missing project files and always rewrites the device config. Never overwrites user-editable files."""
    user_editable_files = {
        Path("platformio.ini"): _PLATFORMIO_INI.format(
            environment=ENVIRONMENT_NAME, platform=PLATFORM, board=board, ota_app_library=OTA_APP_LIBRARY_DIR
        ),
        Path("src") / "main.cpp": _MAIN_CPP,
        Path(".gitignore"): _GITIGNORE,
    }
    device_config = _DEVICE_CONFIG_CPP.format(
        wifi_ssid=_c_string_literal(wifi_ssid),
        wifi_password=_c_string_literal(wifi_password),
        hostname=_c_string_literal(hostname),
        ota_password=_c_string_literal(ota_password),
    )

    (project_dir / "src").mkdir(parents=True, exist_ok=True)
    outcome: dict[str, list[str]] = {"created": [], "kept": [], "rewritten": []}
    for relative_path, content in user_editable_files.items():
        path = project_dir / relative_path
        if path.exists():
            outcome["kept"].append(str(relative_path))
        else:
            path.write_text(content)
            outcome["created"].append(str(relative_path))

    config_path = project_dir / DEVICE_CONFIG_RELATIVE_PATH
    outcome["rewritten" if config_path.exists() else "created"].append(str(DEVICE_CONFIG_RELATIVE_PATH))
    config_path.write_text(device_config)
    return outcome
